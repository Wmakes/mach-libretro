#!/usr/bin/env python3
"""Regenerate raw declarations from the pinned header with clang and a native C probe.
No network, third-party Python packages, or C code in the library build.
"""
from pathlib import Path
import argparse
import json
import os
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / 'vendor/libretro/libretro.h'
CLANG = os.environ.get('CC', 'clang')


def run(*args, **kw):
    return subprocess.check_output([str(a) for a in args], text=True, **kw)


def declarations():
    ast = json.loads(run(CLANG, '-x', 'c', '-std=c11', '-Xclang', '-ast-dump=json', '-fsyntax-only', HEADER))
    return [n for n in ast['inner'] if n.get('name', '').startswith('retro_')]


def split_function(ty):
    m = re.fullmatch(r'(.*?)\s*\(\*\)\((.*)\)', ty)
    if not m:
        raise ValueError('Unsupported callback: ' + ty)
    args = [] if m[2] == 'void' else re.split(r',\s*(?![^()]*\))', m[2])
    return m[1].strip(), args


def mach_type(ty):
    ty = re.sub(r'\b(const|volatile|restrict)\b', '', ty)
    ty = ' '.join(ty.split())
    if '(*)' in ty:
        result, args = split_function(ty)
        return 'fun(' + ', '.join(mach_type(a) for a in args) + ')' + (' ' + mach_type(result) if result != 'void' else '')
    m = re.fullmatch(r'(.*?)((?:\[\d+\])+)', ty)
    if m:
        return ''.join('[' + n + ']' for n in re.findall(r'\[(\d+)\]', m[2])) + mach_type(m[1].strip())
    if ty.endswith('*'):
        base = ty[:-1].strip()
        return 'ptr' if base == 'void' else '*' + mach_type(base)
    ty = re.sub(r'^(struct|union|enum) ', '', ty)
    scalar = {'void': '', '_Bool': 'u8', 'char': 'u8', 'signed char': 'i8', 'unsigned char': 'u8',
              'short': 'i16', 'unsigned short': 'u16', 'int': 'i32', 'unsigned int': 'u32',
              'int8_t': 'i8', 'uint8_t': 'u8', 'int16_t': 'i16', 'uint16_t': 'u16',
              'int32_t': 'i32', 'uint32_t': 'u32', 'int64_t': 'i64', 'uint64_t': 'u64',
              'size_t': 'size_t', 'uintptr_t': 'uintptr_t', 'float': 'f32', 'double': 'f64', '...': '...'}
    if ty in scalar:
        return scalar[ty]
    if ty.startswith('retro_'):
        return ty
    raise ValueError('Unmapped C type: ' + ty)


def constants_and_enums(nodes):
    macros = run(CLANG, '-dM', '-E', '-x', 'c', HEADER)
    names = []
    for line in macros.splitlines():
        m = re.match(r'#define ((?:RETRO_|RETROK)[A-Za-z0-9_]+) (.+)', line)
        if m and m[1] not in ('RETRO_API', 'RETRO_CALLCONV', 'RETRO_HW_FRAME_BUFFER_VALID'):
            names.append(m[1])
    enums = [n for n in nodes if n['kind'] == 'EnumDecl']
    names += [v['name'] for n in enums for v in n.get('inner', []) if v['kind'] == 'EnumConstantDecl']
    # A C compiler determines both the value and C integer type; no Python eval.
    c = '#include "libretro.h"\n#include <stdio.h>\n#define TY(x) _Generic((x), int:"i32", unsigned int:"u32", long:"i64", unsigned long:"u64", long long:"i64", unsigned long long:"u64")\nint main(void) {\n'
    for name in names:
        c += f'printf("{name} %s %lld\\n", TY({name}), (long long)({name}));\n'
    for n in enums:
        c += f'printf("@{n["name"]} %s 0\\n", TY((enum {n["name"]})0));\n'
    c += '}\n'
    with tempfile.TemporaryDirectory(prefix='libretro-generate-') as td:
        src, exe = Path(td)/'values.c', Path(td)/('values.exe' if os.name == 'nt' else 'values')
        src.write_text(c)
        run(CLANG, '-std=c11', '-I', HEADER.parent, src, '-o', exe)
        rows = [line.split() for line in run(exe).splitlines()]
    return rows


def generate():
    nodes = declarations()
    rows = constants_and_enums(nodes)
    lines = ['# Generated by tools/generate.py from vendor/libretro/libretro.h. Do not hand edit.',
             '# Copyright (C) 2010-2024 The RetroArch team; header MIT notice in vendor/libretro/libretro.h.',
             '# C bool = u8 (write only 0 or 1). const is not enforced: honor header pointer ownership.',
             '# Supported targets have 64-bit pointers and size_t; no external library is linked.',
             '$if ($mach.build.pointer_width != 8) { $error("libretro: only 64-bit targets are verified"); }',
             'pub def size_t: u64;', 'pub def uintptr_t: u64;', '', '# Constants and C enumerations']
    for name, ty, value in rows:
        if name.startswith('@'):
            lines.extend(['$if ($mach.build.sys == $mach.sys.windows) {', f'    pub def {name[1:]}: i32;', '}', '$or {', f'    pub def {name[1:]}: u32;', '}'])
        else:
            value = str(int(value))
            if value.startswith('-'):
                value = '(0 - ' + value[1:] + ')'
            lines.append(f'pub val {name}: {ty} = {value};')
    lines += ['', '# Sentinel and function-like header macros',
              'pub val RETRO_HW_FRAME_BUFFER_VALID: ptr = 0xFFFFFFFFFFFFFFFFu64::ptr;',
              'pub fun RETRO_DEVICE_SUBCLASS(base: u32, id: u32) u32 { ret ((id + 1) << 8) | base; }',
              'pub fun RETRO_SENSOR_INDEX(id: u32) u32 { ret id >> 8; }',
              'pub fun RETRO_SENSOR_BASE(id: u32) u32 { ret id & 255; }',
              'pub fun RETRO_SENSOR_SUBDEVICE(index: u32, id: u32) u32 { ret (index << 8) | id; }',
              '', '# Callback signatures, scalar aliases and records in header order']
    seen = set()
    for n in nodes:
        kind, name = n['kind'], n['name']
        if kind == 'RecordDecl':
            if name in seen:
                continue
            # Complete definitions replace forward declarations; true opaque types
            # get an empty record solely to distinguish pointers. Never instantiate.
            if not n.get('completeDefinition') and any(x['kind'] == kind and x['name'] == name and x.get('completeDefinition') for x in nodes):
                continue
            seen.add(name)
            if not n.get('completeDefinition'):
                lines.append('# Opaque C handle: pointer use only; size/layout are intentionally unspecified.')
            lines.append('pub ' + ('uni' if n['tagUsed'] == 'union' else 'rec') + ' ' + name + ' {')
            for f in n.get('inner', []):
                if f['kind'] == 'FieldDecl':
                    if f.get('isBitfield') or not f.get('name'):
                        raise ValueError('Unsupported field in ' + name)
                    lines.append(f'    {f["name"]}: {mach_type(f["type"]["qualType"])};')
                elif f['kind'] == 'RecordDecl':
                    raise ValueError('Nested record requires explicit handling: ' + name)
            lines += ['}', '']
        elif kind == 'TypedefDecl':
            lines.append(f'pub def {name}: {mach_type(n["type"]["qualType"])};')
    text = '\n'.join(lines) + '\n'
    return text, nodes, rows


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text, nodes, rows = generate()
    dest = ROOT/'src/c.mach'
    if args.check:
        # Formatting is a separate compiler operation; compare token streams.
        if re.sub(r'\s+', '', text) != re.sub(r'\s+', '', dest.read_text()):
            raise SystemExit('Bindings differ from pinned header; run python3 tools/generate.py')
    else:
        dest.write_text(text)
    print(f'{len(rows)} constants/enum types; {sum(n["kind"] == "TypedefDecl" for n in nodes)} typedefs; {sum(n["kind"] == "RecordDecl" and bool(n.get("completeDefinition")) for n in nodes)} complete records/unions')
